// Package clientgen generates a typed Go HTTP client from a service's routes.
// Each route becomes a method whose request and response types are the handler's
// In and Out types, so a caller gets a compile-checked client for another
// service. Path parameters become string arguments.
package clientgen

import (
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"path"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// Route is one route to generate a method for.
type Route struct {
	Method    string
	Path      string
	Operation string
	In        string
	Out       string
	InImport  string
	OutImport string
	// InType and OutType are In and Out with every named type qualified by
	// its full import path ("example.com/app/contracts.Page[example.com/app/models.Item]").
	// When set they take precedence over In/InImport and Out/OutImport, which
	// cannot name the package of a type nested in a slice, map or pointer.
	InType  string
	OutType string
}

// stdImports are the packages the generated client uses, by import path.
var stdImports = map[string]string{
	"bytes":         "bytes",
	"context":       "context",
	"encoding/json": "json",
	"fmt":           "fmt",
	"io":            "io",
	"net/http":      "http",
	"net/url":       "url",
	"strings":       "strings",
}

// reservedIdents are names the generated methods use for their own receiver,
// arguments and locals; path parameters and import aliases must avoid them.
var reservedIdents = map[string]bool{"c": true, "ctx": true, "in": true, "out": true, "err": true}

// Generate returns formatted Go source for a client named after service, in
// package pkg. It returns an error if the generated source is not valid Go or
// fails to type-check.
func Generate(pkg, service string, routes []Route) (string, error) {
	typeName := exportName(service) + "Client"

	// Qualify every In and Out, then give each imported package an alias that
	// is unique in the file, so same-named packages and types never clash.
	ins := make([]string, len(routes))
	outs := make([]string, len(routes))
	for i, r := range routes {
		ins[i] = qualified(r.In, r.InImport, r.InType)
		outs[i] = qualified(r.Out, r.OutImport, r.OutType)
	}
	taken := map[string]bool{typeName: true, "New" + typeName: true}
	for _, name := range stdImports {
		taken[name] = true
	}
	aliases := map[string]string{}
	for _, q := range append(append([]string(nil), ins...), outs...) {
		rewriteTypes(q, func(p, name string) string {
			if _, ok := aliases[p]; !ok {
				aliases[p] = ""
			}
			return name
		})
	}
	for _, p := range sortedKeys(aliases) {
		if name, ok := stdImports[p]; ok {
			aliases[p] = name
			continue
		}
		aliases[p] = uniqueIdent(aliasBase(p), taken)
	}
	render := func(q string) string {
		return typeExpr(rewriteTypes(q, func(p, name string) string { return aliases[p] + "." + name }))
	}

	names := methodNames(routes)
	needURL := false
	for _, r := range routes {
		if paramRE.MatchString(r.Path) {
			needURL = true
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by \"bosun gen client\". DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import (\n")
	for _, imp := range []string{"bytes", "context", "encoding/json", "fmt", "io", "net/http", "net/url", "strings"} {
		if imp == "net/url" && !needURL {
			if _, used := aliases[imp]; !used {
				continue
			}
		}
		fmt.Fprintf(&b, "\t%q\n", imp)
	}
	var user []string
	for _, p := range sortedKeys(aliases) {
		if _, ok := stdImports[p]; !ok {
			user = append(user, p)
		}
	}
	if len(user) > 0 {
		b.WriteString("\n")
		for _, p := range user {
			fmt.Fprintf(&b, "\t%s %q\n", aliases[p], p)
		}
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "// %s calls the %s service over HTTP.\n", typeName, service)
	fmt.Fprintf(&b, "type %s struct {\n\tBaseURL string\n\tHTTP    *http.Client\n}\n\n", typeName)
	fmt.Fprintf(&b, "// New%s returns a client for the service at baseURL.\n", typeName)
	fmt.Fprintf(&b, "func New%s(baseURL string) *%s {\n\treturn &%s{BaseURL: baseURL, HTTP: http.DefaultClient}\n}\n\n", typeName, typeName, typeName)

	fmt.Fprintf(&b, `func (c *%s) do(ctx context.Context, method, path string, in, out any) error {
	var body io.Reader
	if in != nil {
		raw, err := json.Marshal(in)
		if err != nil {
			return err
		}
		body = bytes.NewReader(raw)
	}
	req, err := http.NewRequestWithContext(ctx, method, strings.TrimRight(c.BaseURL, "/")+path, body)
	if err != nil {
		return err
	}
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	hc := c.HTTP
	if hc == nil {
		hc = http.DefaultClient
	}
	resp, err := hc.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode/100 != 2 {
		b, _ := io.ReadAll(io.LimitReader(resp.Body, 4096))
		return fmt.Errorf("%%s %%s: %%s: %%s", method, path, resp.Status, strings.TrimSpace(string(b)))
	}
	if out != nil {
		return json.NewDecoder(resp.Body).Decode(out)
	}
	return nil
}

`, typeName)

	// Path parameters must not shadow the receiver, locals or an import.
	paramTaken := map[string]bool{}
	for name := range reservedIdents {
		paramTaken[name] = true
	}
	for _, alias := range aliases {
		paramTaken[alias] = true
	}
	for _, name := range stdImports {
		paramTaken[name] = true
	}
	for i, r := range routes {
		writeMethod(&b, typeName, names[i], r, render(ins[i]), render(outs[i]), paramTaken)
	}

	src := b.String()
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return src, fmt.Errorf("clientgen: generated invalid Go: %w", err)
	}
	if err := check(formatted); err != nil {
		return string(formatted), fmt.Errorf("clientgen: generated client does not compile: %w", err)
	}
	return string(formatted), nil
}

var paramRE = regexp.MustCompile(`\{([a-zA-Z_][a-zA-Z0-9_]*)(\.\.\.)?\}`)

func writeMethod(b *strings.Builder, typeName, name string, r Route, inExpr, outExpr string, paramTaken map[string]bool) {
	params := paramRE.FindAllStringSubmatch(r.Path, -1)

	var args []string
	args = append(args, "ctx context.Context")
	idents := map[string]string{}
	for _, p := range params {
		id := p[1]
		if paramTaken[id] || token.IsKeyword(id) || types.Universe.Lookup(id) != nil {
			id += "Param"
		}
		idents[p[1]] = id
		args = append(args, id+" string")
	}
	hasIn := inExpr != "struct{}" && inExpr != ""
	if hasIn {
		args = append(args, "in "+inExpr)
	}
	if outExpr == "" {
		outExpr = "struct{}"
	}

	pathExpr := pathExpr(r.Path, idents)
	inArg := "nil"
	if hasIn {
		inArg = "in"
	}

	fmt.Fprintf(b, "func (c *%s) %s(%s) (%s, error) {\n", typeName, name, strings.Join(args, ", "), outExpr)
	if outExpr == "struct{}" {
		fmt.Fprintf(b, "\treturn struct{}{}, c.do(ctx, %q, %s, %s, nil)\n", r.Method, pathExpr, inArg)
	} else {
		fmt.Fprintf(b, "\tvar out %s\n", outExpr)
		fmt.Fprintf(b, "\terr := c.do(ctx, %q, %s, %s, &out)\n", r.Method, pathExpr, inArg)
		b.WriteString("\treturn out, err\n")
	}
	b.WriteString("}\n\n")
}

// pathExpr turns "/users/{id}/posts" into a Go string expression that escapes
// each parameter: `"/users/" + url.PathEscape(id) + "/posts"`. idents maps a
// parameter to its Go argument name.
func pathExpr(path string, idents map[string]string) string {
	if !strings.Contains(path, "{") {
		return fmt.Sprintf("%q", path)
	}
	var parts []string
	last := 0
	for _, loc := range paramRE.FindAllStringSubmatchIndex(path, -1) {
		if loc[0] > last {
			parts = append(parts, fmt.Sprintf("%q", path[last:loc[0]]))
		}
		name := path[loc[2]:loc[3]]
		parts = append(parts, "url.PathEscape("+idents[name]+")")
		last = loc[1]
	}
	if last < len(path) {
		parts = append(parts, fmt.Sprintf("%q", path[last:]))
	}
	return strings.Join(parts, " + ")
}

var closureRE = regexp.MustCompile(`^func[0-9]+$`)

// methodNames names each route's method after its handler. Closures, and
// handlers whose name is not usable, are named from the HTTP method and path.
// A name used by more than one route is prefixed with its controller, and any
// that still collide get a numeric suffix.
func methodNames(routes []Route) []string {
	names := make([]string, len(routes))
	count := map[string]int{"BaseURL": 1, "HTTP": 1} // the client's fields
	for i, r := range routes {
		names[i] = methodName(r)
		count[names[i]]++
	}
	for i, r := range routes {
		if ctrl := controllerName(r.Operation); count[names[i]] > 1 && ctrl != "" {
			names[i] = exportName(ctrl) + names[i]
		}
	}
	taken := map[string]bool{"BaseURL": true, "HTTP": true}
	for i := range names {
		names[i] = uniqueIdent(names[i], taken)
	}
	return names
}

func methodName(r Route) string {
	// operation looks like "pkg.(*Controller).Method-fm", "pkg.Method-fm" or,
	// for a closure, "pkg.(*Controller).Routes.func1".
	op := strings.TrimSuffix(r.Operation, "-fm")
	if i := strings.LastIndex(op, "."); i >= 0 {
		op = op[i+1:]
	}
	if op != "" && isIdent(op) && !closureRE.MatchString(op) {
		return exportName(op)
	}
	// fallback: Method + last path segment
	seg := strings.Trim(paramRE.ReplaceAllString(r.Path, ""), "/")
	if i := strings.LastIndex(seg, "/"); i >= 0 {
		seg = seg[i+1:]
	}
	name := exportName(strings.ToLower(r.Method))
	if seg != "" {
		name += exportName(seg)
	}
	return name
}

// controllerName returns the receiver type in an operation such as
// "example.com/app.(*Users).List-fm", or the enclosing function of a closure.
func controllerName(op string) string {
	if i := strings.LastIndex(op, "/"); i >= 0 {
		op = op[i+1:]
	}
	if i := strings.Index(op, "."); i >= 0 {
		op = op[i+1:] // drop the package name
	}
	op = strings.NewReplacer("(*", "", "(", "", ")", "").Replace(op)
	parts := strings.Split(op, ".")
	if len(parts) < 2 {
		return ""
	}
	return parts[0]
}

// qualified returns a type with every named type written as
// "importpath.Name". A manifest's in_type/out_type already is; otherwise the
// reflect string's leading package name is replaced by the import path (type
// arguments of a generic type are already qualified by path).
func qualified(t, imp, full string) string {
	if full != "" {
		return full
	}
	if imp == "" {
		return t
	}
	if i := strings.Index(t, "."); i >= 0 {
		return imp + t[i:]
	}
	return t
}

// rewriteTypes calls fn for every qualified name "importpath.Name" in the type
// expression t and replaces it with fn's result. Struct tags are left alone.
func rewriteTypes(t string, fn func(path, name string) string) string {
	var b strings.Builder
	for i := 0; i < len(t); {
		ch := t[i]
		switch {
		case ch == '"' || ch == '`':
			j := i + 1
			for j < len(t) && t[j] != ch {
				if ch == '"' && t[j] == '\\' {
					j++
				}
				j++
			}
			j = min(j+1, len(t))
			b.WriteString(t[i:j])
			i = j
		case isPathByte(ch):
			j := i
			for j < len(t) && isPathByte(t[j]) {
				j++
			}
			tok := t[i:j]
			if k := strings.LastIndex(tok, "."); k > 0 && tok[0] != '.' {
				tok = fn(tok[:k], tok[k+1:])
			}
			b.WriteString(tok)
			i = j
		default:
			b.WriteByte(ch)
			i++
		}
	}
	return b.String()
}

func isPathByte(c byte) bool {
	return c == '_' || c == '-' || c == '.' || c == '/' || c == '~' ||
		(c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')
}

var majorVersionRE = regexp.MustCompile(`^v[0-9]+$`)

// aliasBase derives an import alias from an import path: its last element
// (skipping a /vN major-version suffix), reduced to identifier characters.
func aliasBase(p string) string {
	base := path.Base(p)
	if majorVersionRE.MatchString(base) && path.Dir(p) != "." {
		base = path.Base(path.Dir(p))
	}
	var b strings.Builder
	for _, r := range base {
		if r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
		}
	}
	s := b.String()
	if s == "" || (s[0] >= '0' && s[0] <= '9') {
		s = "pkg" + s
	}
	return s
}

// uniqueIdent returns base, or base with a numeric suffix, such that it is not
// in taken, a keyword, a predeclared identifier or a generated local; it then
// marks the result taken.
func uniqueIdent(base string, taken map[string]bool) string {
	name := base
	for n := 2; taken[name] || reservedIdents[name] || token.IsKeyword(name) || types.Universe.Lookup(name) != nil; n++ {
		name = base + strconv.Itoa(n)
	}
	taken[name] = true
	return name
}

// typeExpr normalizes a reflect type string for use in generated code.
func typeExpr(t string) string {
	switch t {
	case "struct {}":
		return "struct{}"
	case "interface {}":
		return "any"
	default:
		return t
	}
}

// check type-checks the generated file. Imports are not resolved (the
// importer fails for every package, and the checker then ignores uses of
// them), so it catches the generator's own mistakes: duplicate methods,
// clashing parameters and unused imports.
func check(src []byte) error {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "client.go", src, 0)
	if err != nil {
		return err
	}
	var errs []string
	conf := types.Config{
		Importer: noImporter{},
		Error: func(err error) {
			if te, ok := err.(types.Error); ok && strings.HasPrefix(te.Msg, "could not import") {
				return
			}
			errs = append(errs, err.Error())
		},
	}
	_, _ = conf.Check(f.Name.Name, fset, []*ast.File{f}, nil)

	// The checker does not report unused imports it could not resolve.
	used := map[string]bool{}
	ast.Inspect(f, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				used[id.Name] = true
			}
		}
		return true
	})
	for _, imp := range f.Imports {
		p, _ := strconv.Unquote(imp.Path.Value)
		name := path.Base(p)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		if !used[name] {
			errs = append(errs, fmt.Sprintf("%s: %q imported and not used", fset.Position(imp.Pos()), p))
		}
	}
	if len(errs) > 0 {
		return errors.New(strings.Join(errs, "; "))
	}
	return nil
}

type noImporter struct{}

func (noImporter) Import(p string) (*types.Package, error) {
	return nil, fmt.Errorf("%s not resolved", p)
}

// exportName turns s into an exported Go identifier, treating any character
// that cannot appear in one as a word break.
func exportName(s string) string {
	s = strings.TrimSpace(s)
	var b strings.Builder
	upper := true
	for _, r := range s {
		if !(r >= 'a' && r <= 'z') && !(r >= 'A' && r <= 'Z') && !(r >= '0' && r <= '9') {
			upper = true
			continue
		}
		if upper {
			b.WriteString(strings.ToUpper(string(r)))
			upper = false
		} else {
			b.WriteRune(r)
		}
	}
	out := b.String()
	if out == "" {
		return "Client"
	}
	if out[0] >= '0' && out[0] <= '9' {
		out = "X" + out
	}
	return out
}

func isIdent(s string) bool {
	for i, r := range s {
		if r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') {
			continue
		}
		if i > 0 && r >= '0' && r <= '9' {
			continue
		}
		return false
	}
	return s != ""
}

func sortedKeys[V any](m map[string]V) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
