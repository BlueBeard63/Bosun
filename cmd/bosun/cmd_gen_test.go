package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func runGenRegistry(t *testing.T, args ...string) (string, error) {
	t.Helper()
	cmd := genRegistryCmd()
	var stderr bytes.Buffer
	cmd.SetErr(&stderr)
	cmd.SetOut(&stderr)
	cmd.SetArgs(args)
	err := cmd.Execute()
	return stderr.String(), err
}

func TestGenRegistryWriteAndCheck(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"go.mod":         "module example.com/app\n\ngo 1.22\n",
		"main.go":        "package main\n\nfunc main() {}\n",
		"orders/ctrl.go": "package orders\n\nimport \"github.com/bluebeard63/bosun\"\n\ntype Ctrl struct{}\n\nvar _ = bosun.Controller[Ctrl](\"/orders\")\n",
	}
	for rel, body := range files {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	if _, err := runGenRegistry(t, "--dir", dir, "--check"); err == nil {
		t.Fatal("--check should fail before the file exists")
	}
	msg, err := runGenRegistry(t, "--dir", dir)
	if err != nil {
		t.Fatalf("generate: %v (%s)", err, msg)
	}
	src, err := os.ReadFile(filepath.Join(dir, "zz_bosun_registry.go"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(src), `_ "example.com/app/orders" // Controller[Ctrl]`) ||
		!strings.HasPrefix(string(src), "// Code generated by bosun gen registry. DO NOT EDIT.") {
		t.Fatalf("generated file:\n%s", src)
	}
	if _, err := runGenRegistry(t, "--dir", dir, "--check"); err != nil {
		t.Fatalf("--check after generate: %v", err)
	}

	// Adding a registering package makes the file stale.
	p := filepath.Join(dir, "billing", "svc.go")
	_ = os.MkdirAll(filepath.Dir(p), 0o755)
	_ = os.WriteFile(p, []byte("package billing\n\nimport \"github.com/bluebeard63/bosun\"\n\ntype Svc struct{}\n\nvar _ = bosun.Service[Svc]()\n"), 0o644)
	if _, err := runGenRegistry(t, "--dir", dir, "--check"); err == nil || !strings.Contains(err.Error(), "out of date") {
		t.Fatalf("--check should report stale file, got %v", err)
	}
}

func TestGenRegistryDocs(t *testing.T) {
	dir := t.TempDir()
	files := map[string]string{
		"go.mod":  "module example.com/app\n\ngo 1.22\n\nrequire github.com/bluebeard63/bosun v0.8.0\n",
		"main.go": "package main\n\n// Out is the response.\ntype Out struct{}\n\nfunc main() {}\n",
	}
	for rel, body := range files {
		if err := os.WriteFile(filepath.Join(dir, rel), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	read := func() string {
		t.Helper()
		src, err := os.ReadFile(filepath.Join(dir, "zz_bosun_registry.go"))
		if err != nil {
			t.Fatal(err)
		}
		return string(src)
	}
	if msg, err := runGenRegistry(t, "--dir", dir); err != nil {
		t.Fatalf("generate: %v (%s)", err, msg)
	}
	if src := read(); !strings.Contains(src, `"main.Out": "Out is the response."`) {
		t.Fatalf("doc comments missing:\n%s", src)
	}
	if msg, err := runGenRegistry(t, "--dir", dir, "--no-docs"); err != nil {
		t.Fatalf("generate --no-docs: %v (%s)", err, msg)
	}
	if src := read(); strings.Contains(src, "RegisterDocComments") {
		t.Fatalf("--no-docs still wrote doc comments:\n%s", src)
	}
}

func TestGenClientReadsQualifiedTypes(t *testing.T) {
	dir := t.TempDir()
	manifest := `{"service": "billing", "routes": [{"method": "GET", "path": "/users", "operation": "app.(*Users).List-fm",
		"in": "struct {}", "out": "[]contracts.User", "out_type": "[]example.com/app/contracts.User"}]}`
	in := filepath.Join(dir, "manifest.json")
	out := filepath.Join(dir, "client.go")
	if err := os.WriteFile(in, []byte(manifest), 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := genClientCmd()
	cmd.SetArgs([]string{in, "--out", out})
	if err := cmd.Execute(); err != nil {
		t.Fatal(err)
	}
	src, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(src), `contracts "example.com/app/contracts"`) ||
		!strings.Contains(string(src), "List(ctx context.Context) ([]contracts.User, error)") {
		t.Fatalf("generated client:\n%s", src)
	}
}
